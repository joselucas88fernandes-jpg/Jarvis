    def self_inspect(self) -> dict:
        """
        Inspects the project directory and returns a tree structure.
        """
        file_tree = {}
        for root, dirs, files in os.walk(self.project_root):
            if '.git' in dirs:
                dirs.remove('.git')  # Don't include the .git directory
            if '.idea' in dirs:
                dirs.remove('.idea') # Don't include the .idea directory

            root_path = Path(root).relative_to(self.project_root)
            file_tree[str(root_path)] = {
                "directories": dirs,
                "files": files
            }
        return file_tree

