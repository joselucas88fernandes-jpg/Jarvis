    def create_sandbox(self, new_code: str, test_code: str):
        """
        Creates a temporary directory to write and test new code.
        """
        with tempfile.TemporaryDirectory() as temp_dir:
            temp_path = Path(temp_dir)
            new_module_path = temp_path / "new_module.py"
            test_module_path = temp_path / "test_module.py"

            with open(new_module_path, "w") as f:
                f.write(new_code)
            with open(test_module_path, "w") as f:
                f.write(test_code)

            logging.info(f"Sandbox created at: {temp_dir}")
            return self.run_tests(test_module_path)

    def run_tests(self, test_path: Path) -> bool:
        """
        Runs unit tests in the sandbox.
        """
        loader = unittest.TestLoader()
        suite = loader.discover(start_dir=test_path.parent, pattern=test_path.name)
        runner = unittest.TextTestRunner()
        result = runner.run(suite)
        return result.wasSuccessful()

    def commit_changes(self, file_path: str, commit_message: str):
        """
        Commits the verified changes to the codebase.
        """
        if self.repo.is_dirty(untracked_files=True):
            self.repo.git.add(file_path)
            self.repo.index.commit(commit_message)
            logging.info(f"Committed changes to {file_path} with message: {commit_message}")

    def dynamic_reload(self, module_name: str):
        """
        Dynamically reloads an updated module.
        """
        try:
            module = importlib.import_module(module_name)
            importlib.reload(module)
            logging.info(f"Successfully reloaded module: {module_name}")
        except (ImportError, ModuleNotFoundError) as e:
            logging.error(f"Failed to reload module {module_name}: {e}")

